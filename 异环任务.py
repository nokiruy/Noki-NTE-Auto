def 等待事件(事件, 总超时秒数):
    """
    等待事件保持设置状态，最多等待 total_timeout 秒。
    每 0.5 秒检查一次事件状态，若事件被清除则提前返回。

    参数:
        事件: threading.Event 对象
        总超时秒数: 最大等待时间（秒），若 ≤0 则立即超时

    返回:
        bool: 若在超时内事件始终保持设置状态且未超时，返回 True；
              若事件被清除或超时（包括初始超时≤0），返回 False。
    """
    # 处理非正超时：立即返回 False（表示等待失败/超时）
    if 总超时秒数 <= 0:
        return False

    起始时间 = time.time()
    已用时间 = 0.0

    while 已用时间 < 总超时秒数:
        if not 事件.is_set():
            return False   # 事件被清除，提前结束

        剩余时间 = 总超时秒数 - 已用时间
        本次休眠 = min(0.5, 剩余时间)
        time.sleep(本次休眠)
        已用时间 = time.time() - 起始时间

    # 超时后，若事件仍为设置状态，则说明一直保持到结束（实际并未超时成功？）
    # 但按函数语义，超时后应返回 False，因为等待已结束（可能事件仍为设置状态，但超时也算失败）
    # 这里返回 False 表示等待结束（超时），即使事件仍为设置状态，也认为未成功等待到完整时长？
    # 更清晰：如果超时了，不管事件状态如何，都返回 False（表示未在有效期内保持）
    return False

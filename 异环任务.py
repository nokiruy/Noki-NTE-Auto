def 获取虚拟键码(键名: str) -> int:
    # noinspection NonAsciiCharacters
    键名 = 键名.strip().lower()
    if len(键名) == 1 and 键名.isalpha():
        return ord(键名.upper())
    if len(键名) == 1 and 键名.isdigit():
        return ord(键名)
    if 键名 in KEY_MAP:
        return KEY_MAP[键名]
    raise ValueError(f"不支持的按键名称: {键名}")


